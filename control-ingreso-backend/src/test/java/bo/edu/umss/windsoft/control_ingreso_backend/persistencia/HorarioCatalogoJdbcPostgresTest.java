package bo.edu.umss.windsoft.control_ingreso_backend.persistencia;

import bo.edu.umss.windsoft.control_ingreso_backend.aplicacion.*;
import bo.edu.umss.windsoft.control_ingreso_backend.dominio.*;
import bo.edu.umss.windsoft.control_ingreso_backend.dominio.exception.SolicitudInvalidaException;
import java.nio.file.*;
import java.sql.*;
import java.util.*;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.condition.EnabledIfSystemProperty;
import org.springframework.beans.factory.config.YamlPropertiesFactoryBean;
import org.springframework.core.io.FileSystemResource;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.SingleConnectionDataSource;
import org.springframework.mock.web.MockMultipartFile;
import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.Mockito.*;

@EnabledIfSystemProperty(named="jdbc.batch.integration", matches="true")
class HorarioCatalogoJdbcPostgresTest {
    @Test void horarioFisicaRealSeImportaEnLotesSinDuplicarNiCambiarIds() throws Exception {
        String ruta=System.getProperty("horario.fisica.pdf");
        org.junit.jupiter.api.Assumptions.assumeTrue(ruta!=null);
        byte[] pdf=Files.readAllBytes(Path.of(ruta));
        var yaml=new YamlPropertiesFactoryBean();
        yaml.setResources(new FileSystemResource("src/main/resources/application.yaml"),new FileSystemResource("src/main/resources/application-local.yaml"));
        var cfg=yaml.getObject();
        try(var c=DriverManager.getConnection(cfg.getProperty("spring.datasource.url"),cfg.getProperty("spring.datasource.username"),cfg.getProperty("spring.datasource.password"))) {
            c.setAutoCommit(false);
            try {
                try(var st=c.createStatement()) {
                    st.execute("CREATE TEMP TABLE asignatura (idasignatura integer PRIMARY KEY,nombreasignatura text,codigooficial text UNIQUE)");
                    st.execute("CREATE TEMP TABLE grupo (idgrupo integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,idasignatura integer REFERENCES pg_temp.asignatura,nombregrupo text,estadogrupo boolean,idsemestre integer DEFAULT 1, UNIQUE(idasignatura,nombregrupo,idsemestre))");
                    st.execute("INSERT INTO pg_temp.asignatura VALUES (1,'ALGEBRA I','2008019')");
                }
                var jdbc=new JdbcTemplate(new SingleConnectionDataSource(c,true));
                var asignaturas=mock(AsignaturaRepository.class); var grupos=mock(GrupoRepository.class);
                when(asignaturas.findAll()).thenAnswer(i -> jdbc.query("SELECT * FROM pg_temp.asignatura",(rs,n) -> {
                    var a=new Asignatura();a.setIdAsignatura(rs.getInt("idasignatura"));a.setNombreAsignatura(rs.getString("nombreasignatura"));a.setCodigoOficial(rs.getString("codigooficial"));return a;
                }));
                when(grupos.findAll()).thenAnswer(i -> jdbc.query("SELECT * FROM pg_temp.grupo WHERE idsemestre=1",(rs,n) -> {
                    var g=new Grupo(rs.getInt("idasignatura"),rs.getString("nombregrupo"),null);g.setIdGrupo(rs.getInt("idgrupo"));g.setEstadoGrupo(rs.getBoolean("estadogrupo"));return g;
                }));
                var servicio=new HorarioImportacionService(new LectorHorarioPdf(),asignaturas,grupos,new HorarioCatalogoJdbcRepository(jdbc));
                var archivo=new MockMultipartFile("archivo","fisica.pdf","application/pdf",pdf);
                var previo=servicio.previsualizar(archivo);
                int materias=(int)previo.filas().stream().map(f->f.codigoAsignatura()).distinct().count();
                long start=System.nanoTime();var primera=servicio.confirmarAutomaticamente(archivo);
                double ms=(System.nanoTime()-start)/1_000_000.0;
                assertEquals(materias,primera.asignaturasCreadas());assertEquals(previo.filas().size(),primera.gruposCreados());
                assertEquals("2008019",jdbc.queryForObject("SELECT codigooficial FROM pg_temp.asignatura WHERE idasignatura=1",String.class));
                assertEquals(2,jdbc.queryForObject("SELECT count(*) FROM pg_temp.asignatura WHERE nombreasignatura='ALGEBRA I'",Integer.class));
                assertEquals(0,jdbc.queryForObject("SELECT count(*) FROM pg_temp.grupo WHERE idasignatura=1",Integer.class));
                var ids=jdbc.queryForList("SELECT idgrupo FROM pg_temp.grupo ORDER BY idgrupo",Integer.class);
                var segunda=servicio.confirmarAutomaticamente(archivo);
                assertEquals(0,segunda.asignaturasCreadas());assertEquals(0,segunda.gruposCreados());
                assertEquals(ids,jdbc.queryForList("SELECT idgrupo FROM pg_temp.grupo ORDER BY idgrupo",Integer.class));
                assertEquals(materias,segunda.asignaturasExistentes());assertEquals(ids.size(),segunda.gruposExistentes());
                jdbc.update("UPDATE pg_temp.grupo SET estadogrupo=false WHERE idgrupo=?",ids.getFirst());
                assertThrows(SolicitudInvalidaException.class,()->servicio.confirmarAutomaticamente(archivo));
                assertEquals(ids.size(),jdbc.queryForObject("SELECT count(*) FROM pg_temp.grupo",Integer.class));
                System.out.printf(Locale.ROOT,"HORARIO_FISICA materias=%d, grupos=%d, importacion_ms=%.3f, reimportacion=sin_duplicados, rollback=true%n",materias,ids.size(),ms);
            } finally {c.rollback();}
        }
    }
}
