CREATE TABLE IF NOT EXISTS semestre_docente (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 idsemestre INTEGER NOT NULL REFERENCES semestre,
 codigo VARCHAR(40) NOT NULL, asignatura TEXT NOT NULL, grupo VARCHAR(50) NOT NULL,
 nombre TEXT NOT NULL, apellido TEXT NOT NULL, ci TEXT NOT NULL,
 sis TEXT NOT NULL, correo TEXT NOT NULL, telefono TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS semestre_docente_periodo ON semestre_docente(idsemestre);
