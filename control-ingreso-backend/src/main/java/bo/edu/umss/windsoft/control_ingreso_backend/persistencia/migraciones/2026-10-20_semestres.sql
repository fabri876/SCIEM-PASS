-- Ejecutar dentro de una transacción. No borra cuentas, grupos ni inscripciones.
SET LOCAL lock_timeout = '8s';
LOCK TABLE examen, horarioregular, grupo, docentegrupo, estudiantegrupo, ayudantegrupo IN ACCESS EXCLUSIVE MODE;
CREATE TABLE IF NOT EXISTS semestre (
 idsemestre INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 anio INTEGER NOT NULL CHECK (anio BETWEEN 2000 AND 2200), numero INTEGER NOT NULL CHECK(numero IN (1,2)),
 estado VARCHAR(12) NOT NULL CHECK(estado IN ('ACTUAL','FINALIZADO')),
 observaciones TEXT NOT NULL DEFAULT '', simulado BOOLEAN NOT NULL DEFAULT false,
 pdf BYTEA, pdf_original BYTEA, creado TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(anio,numero,simulado)
);
CREATE UNIQUE INDEX IF NOT EXISTS semestre_un_actual ON semestre(estado) WHERE estado='ACTUAL';
INSERT INTO semestre(anio,numero,estado,observaciones)
SELECT 2026,2,'ACTUAL','Datos existentes al habilitar el historial de semestres.' WHERE NOT EXISTS(SELECT 1 FROM semestre WHERE estado='ACTUAL');
CREATE OR REPLACE FUNCTION semestre_actual_id() RETURNS INTEGER LANGUAGE SQL STABLE AS $$ SELECT idsemestre FROM semestre WHERE estado='ACTUAL' $$;
ALTER TABLE grupo ADD COLUMN IF NOT EXISTS idsemestre INTEGER REFERENCES semestre;
ALTER TABLE examen ADD COLUMN IF NOT EXISTS idsemestre INTEGER REFERENCES semestre;
ALTER TABLE horarioregular ADD COLUMN IF NOT EXISTS idsemestre INTEGER REFERENCES semestre;
UPDATE grupo SET idsemestre=semestre_actual_id() WHERE idsemestre IS NULL;
UPDATE examen SET idsemestre=semestre_actual_id() WHERE idsemestre IS NULL;
UPDATE horarioregular SET idsemestre=semestre_actual_id() WHERE idsemestre IS NULL;
ALTER TABLE grupo ALTER COLUMN idsemestre SET DEFAULT semestre_actual_id(), ALTER COLUMN idsemestre SET NOT NULL;
ALTER TABLE examen ALTER COLUMN idsemestre SET DEFAULT semestre_actual_id(), ALTER COLUMN idsemestre SET NOT NULL;
ALTER TABLE horarioregular ALTER COLUMN idsemestre SET DEFAULT semestre_actual_id(), ALTER COLUMN idsemestre SET NOT NULL;
DROP INDEX IF EXISTS uk_grupo_nombre_normalizado;
CREATE UNIQUE INDEX uk_grupo_nombre_normalizado ON grupo(idsemestre,idasignatura,upper(btrim(nombregrupo)));
ALTER TABLE estudiantegrupo ADD COLUMN IF NOT EXISTS idsemestre INTEGER REFERENCES semestre;
UPDATE estudiantegrupo eg SET idsemestre=g.idsemestre FROM grupo g WHERE eg.idgrupo=g.idgrupo AND eg.idsemestre IS NULL;
ALTER TABLE estudiantegrupo ALTER COLUMN idsemestre SET NOT NULL;
ALTER TABLE estudiantegrupo DROP CONSTRAINT IF EXISTS uk_estudiante_asignatura;
CREATE UNIQUE INDEX IF NOT EXISTS uk_estudiante_asignatura_semestre ON estudiantegrupo(idusuario,idasignatura,idsemestre);
CREATE OR REPLACE FUNCTION derivar_asignatura_inscripcion() RETURNS trigger LANGUAGE plpgsql SET search_path=pg_catalog,public AS $$
BEGIN
 SELECT idasignatura,idsemestre INTO NEW.idasignatura,NEW.idsemestre FROM grupo WHERE idgrupo=NEW.idgrupo;
 IF NEW.idasignatura IS NULL THEN RAISE EXCEPTION 'El grupo no existe.' USING ERRCODE='23503'; END IF;
 RETURN NEW;
END $$;
CREATE TABLE IF NOT EXISTS semestre_fila (
 idsemestre INTEGER NOT NULL REFERENCES semestre, codigo VARCHAR(40) NOT NULL, asignatura TEXT NOT NULL,
 grupo VARCHAR(50) NOT NULL, docentes TEXT NOT NULL, PRIMARY KEY(idsemestre,codigo,grupo)
);
-- Se mantiene una copia de nombres al cerrar: editar una cuenta no reescribe el pasado.
CREATE TABLE IF NOT EXISTS semestre_persona (
 idsemestre INTEGER NOT NULL REFERENCES semestre, idusuario INTEGER NOT NULL,
 rol VARCHAR(20) NOT NULL, idgrupo INTEGER NOT NULL, nombre TEXT NOT NULL,
 PRIMARY KEY(idsemestre,idusuario,rol,idgrupo)
);
CREATE OR REPLACE FUNCTION proteger_periodo_academico() RETURNS trigger LANGUAGE plpgsql SET search_path=pg_catalog,public AS $$
DECLARE periodo INTEGER; actual INTEGER;
BEGIN
 SELECT idsemestre INTO actual FROM semestre WHERE estado='ACTUAL' FOR SHARE;
 IF TG_OP='DELETE' THEN periodo=OLD.idsemestre; ELSE periodo=NEW.idsemestre; END IF;
 IF periodo IS DISTINCT FROM actual OR (TG_OP='UPDATE' AND OLD.idsemestre IS DISTINCT FROM actual) THEN
  RAISE EXCEPTION 'El semestre finalizado es de solo lectura.' USING ERRCODE='23514';
 END IF;
 IF TG_OP='DELETE' THEN RETURN OLD; END IF; RETURN NEW;
END $$;
DO $$ DECLARE t TEXT; BEGIN FOREACH t IN ARRAY ARRAY['grupo','examen','horarioregular'] LOOP
 EXECUTE format('DROP TRIGGER IF EXISTS proteger_periodo ON %I',t);
 EXECUTE format('CREATE TRIGGER proteger_periodo BEFORE INSERT OR UPDATE OR DELETE ON %I FOR EACH ROW EXECUTE FUNCTION proteger_periodo_academico()',t);
END LOOP; END $$;
CREATE OR REPLACE FUNCTION proteger_vinculo_semestre() RETURNS trigger LANGUAGE plpgsql SET search_path=pg_catalog,public AS $$
DECLARE periodo INTEGER; actual INTEGER; grupo_id INTEGER;
BEGIN
 SELECT idsemestre INTO actual FROM semestre WHERE estado='ACTUAL' FOR SHARE;
 IF TG_OP='DELETE' THEN grupo_id=OLD.idgrupo; ELSE grupo_id=NEW.idgrupo; END IF;
 SELECT idsemestre INTO periodo FROM grupo WHERE idgrupo=grupo_id;
 IF periodo IS DISTINCT FROM actual THEN RAISE EXCEPTION 'No se puede modificar un grupo histórico.' USING ERRCODE='23514'; END IF;
 IF TG_OP='UPDATE' AND NEW.idgrupo<>OLD.idgrupo AND EXISTS(SELECT 1 FROM grupo WHERE idgrupo=OLD.idgrupo AND idsemestre<>actual) THEN
  RAISE EXCEPTION 'No se puede trasladar una inscripción histórica.' USING ERRCODE='23514'; END IF;
 IF TG_OP='DELETE' THEN RETURN OLD; END IF; RETURN NEW;
END $$;
DO $$ DECLARE t TEXT; BEGIN FOREACH t IN ARRAY ARRAY['docentegrupo','estudiantegrupo','ayudantegrupo'] LOOP
 EXECUTE format('DROP TRIGGER IF EXISTS proteger_vinculo ON %I',t);
 EXECUTE format('CREATE TRIGGER proteger_vinculo BEFORE INSERT OR UPDATE OR DELETE ON %I FOR EACH ROW EXECUTE FUNCTION proteger_vinculo_semestre()',t);
END LOOP; END $$;
