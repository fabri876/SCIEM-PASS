-- Clasificacion del catalogo por plan/carrera y nivel; no divide grupos compartidos.
CREATE TABLE IF NOT EXISTS carrera_plan (
 idcarrera integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 codigo varchar(80) NOT NULL UNIQUE,
 nombre varchar(255) NOT NULL
);
CREATE TABLE IF NOT EXISTS nivel_carrera (
 idnivel integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 idcarrera integer NOT NULL REFERENCES carrera_plan(idcarrera),
 nombre varchar(10) NOT NULL,
 orden integer NOT NULL CHECK (orden > 0),
 UNIQUE(idcarrera,nombre), UNIQUE(idnivel,idcarrera)
);
CREATE TABLE IF NOT EXISTS asignatura_carrera_nivel (
 idasignatura integer NOT NULL REFERENCES asignatura(idasignatura),
 idcarrera integer NOT NULL REFERENCES carrera_plan(idcarrera),
 idnivel integer NOT NULL,
 idsemestre integer NOT NULL DEFAULT semestre_actual_id() REFERENCES semestre(idsemestre),
 PRIMARY KEY(idsemestre,idcarrera,idnivel,idasignatura),
 FOREIGN KEY(idnivel,idcarrera) REFERENCES nivel_carrera(idnivel,idcarrera)
);
CREATE INDEX IF NOT EXISTS ix_clasificacion_asignatura ON asignatura_carrera_nivel(idasignatura,idsemestre);
