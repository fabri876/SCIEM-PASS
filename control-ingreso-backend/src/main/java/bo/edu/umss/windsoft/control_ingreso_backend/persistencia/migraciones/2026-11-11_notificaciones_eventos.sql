-- HU17: hechos persistentes; la ventana pública de próximos exámenes no cambia.
CREATE TABLE IF NOT EXISTS notificacion_evento (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 idexamen integer NOT NULL REFERENCES examen(idexamen) ON DELETE CASCADE,
 destinatario integer REFERENCES usuario(idusuario) ON DELETE CASCADE,
 tipo varchar(30) NOT NULL,
 titulo text NOT NULL,
 descripcion text NOT NULL,
 fecha timestamptz NOT NULL DEFAULT clock_timestamp(),
 clave text NOT NULL UNIQUE
);
CREATE INDEX IF NOT EXISTS ix_notificacion_evento_fecha ON notificacion_evento(fecha DESC,id DESC);
CREATE INDEX IF NOT EXISTS ix_notificacion_evento_destino ON notificacion_evento(destinatario,idexamen);

CREATE OR REPLACE FUNCTION registrar_evento_notificacion() RETURNS trigger
LANGUAGE plpgsql SET search_path=pg_catalog,public AS $$
DECLARE examen_id integer; destino integer; clase text; titulo_aviso text;
 detalle text; identidad text; registro record;
BEGIN
 IF TG_OP='DELETE' THEN registro=OLD; ELSE registro=NEW; END IF;
 IF TG_TABLE_NAME='examen' THEN
   IF NOT NEW.estadoexamen THEN RETURN NEW; END IF;
   examen_id=NEW.idexamen; clase='PROGRAMADO'; titulo_aviso='Examen programado';
   detalle='Se registró un examen.'; identidad='examen:'||examen_id;
 ELSIF TG_TABLE_NAME='ayudante_examen' THEN
   examen_id=registro.idexamen; destino=registro.idayudante;
   IF TG_OP='DELETE' THEN
     IF OLD.estado_asignacion<>'ACTIVO' THEN RETURN OLD; END IF;
     clase='RETIRO'; titulo_aviso='Asignación retirada'; detalle='Ya no estás asignado a este examen.';
   ELSIF NEW.estado_asignacion='ACTIVO' THEN
     IF TG_OP='UPDATE' AND OLD.estado_asignacion='ACTIVO' AND OLD.idambiente IS NOT DISTINCT FROM NEW.idambiente THEN RETURN NEW; END IF;
     clase='ASIGNACION'; titulo_aviso='Asignación a examen'; detalle='Fuiste asignado para colaborar en este examen.';
   ELSE
     IF TG_OP='INSERT' THEN RETURN NEW; END IF;
     IF OLD.estado_asignacion<>'ACTIVO' THEN RETURN NEW; END IF;
     clase='RETIRO'; titulo_aviso='Asignación retirada'; detalle='Ya no estás asignado a este examen.';
   END IF;
   identidad=clase||':'||examen_id||':'||destino||':'||txid_current();
 ELSIF TG_TABLE_NAME='habilitacion' THEN
   IF NEW.estadohabilitacion IS DISTINCT FROM FALSE THEN RETURN NEW; END IF;
   IF TG_OP='UPDATE' AND OLD.estadohabilitacion IS NOT DISTINCT FROM NEW.estadohabilitacion
     AND OLD.observacionhabilitacion IS NOT DISTINCT FROM NEW.observacionhabilitacion THEN RETURN NEW; END IF;
   examen_id=NEW.idexamen; destino=NEW.idusuario;
   clase='INHABILITACION'; titulo_aviso='Inhabilitación para examen';
   detalle=coalesce(nullif(trim(NEW.observacionhabilitacion),''),'Consulte el motivo con su docente.');
   identidad='habilitacion:'||NEW.idhabilitacion||':'||txid_current();
 ELSIF TG_TABLE_NAME='incidencia' THEN
   SELECT idexamen INTO examen_id FROM ambiente WHERE idambiente=NEW.idambiente;
   clase='INCIDENCIA'; titulo_aviso='Incidencia registrada';
   detalle='Incidencia INC-'||NEW.idincidencia||' · Tipo: '||NEW.tipoincidencia;
   identidad='incidencia:'||NEW.idincidencia;
 ELSIF TG_TABLE_NAME='cambio_examen' THEN
   examen_id=NEW.idexamen; clase=NEW.tipo;
   titulo_aviso=CASE WHEN NEW.tipo='AULA' THEN 'Cambio de aula' ELSE 'Cambio de horario' END;
   detalle='Antes: '||NEW.anterior||'. Ahora: '||NEW.actual||'.';
   identidad='cambio:'||NEW.id;
 END IF;
 IF examen_id IS NOT NULL AND EXISTS(SELECT 1 FROM examen WHERE idexamen=examen_id)
    AND (destino IS NULL OR EXISTS(SELECT 1 FROM usuario WHERE idusuario=destino)) THEN
   INSERT INTO notificacion_evento(idexamen,destinatario,tipo,titulo,descripcion,clave)
   VALUES(examen_id,destino,clase,titulo_aviso,detalle,identidad) ON CONFLICT(clave) DO NOTHING;
 END IF;
 IF TG_OP='DELETE' THEN RETURN OLD; END IF; RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS notificar_examen ON examen;
CREATE TRIGGER notificar_examen AFTER INSERT ON examen FOR EACH ROW EXECUTE FUNCTION registrar_evento_notificacion();
DROP TRIGGER IF EXISTS notificar_asignacion ON ayudante_examen;
CREATE TRIGGER notificar_asignacion AFTER INSERT OR UPDATE OR DELETE ON ayudante_examen FOR EACH ROW EXECUTE FUNCTION registrar_evento_notificacion();
DROP TRIGGER IF EXISTS notificar_habilitacion ON habilitacion;
CREATE TRIGGER notificar_habilitacion AFTER INSERT OR UPDATE ON habilitacion FOR EACH ROW EXECUTE FUNCTION registrar_evento_notificacion();
DROP TRIGGER IF EXISTS notificar_incidencia ON incidencia;
CREATE TRIGGER notificar_incidencia AFTER INSERT ON incidencia FOR EACH ROW EXECUTE FUNCTION registrar_evento_notificacion();
DROP TRIGGER IF EXISTS notificar_cambio ON cambio_examen;
CREATE TRIGGER notificar_cambio AFTER INSERT ON cambio_examen FOR EACH ROW EXECUTE FUNCTION registrar_evento_notificacion();

-- Los avisos preexistentes se incorporan ahora, sin inventar su fecha de creación.
INSERT INTO notificacion_evento(idexamen,tipo,titulo,descripcion,clave)
SELECT idexamen,'PROGRAMADO','Examen programado','Examen incorporado a las notificaciones.', 'examen:'||idexamen
FROM examen WHERE estadoexamen AND idsemestre=semestre_actual_id()
 AND fechaexamen >= (CURRENT_TIMESTAMP AT TIME ZONE 'America/La_Paz')::date
ON CONFLICT(clave) DO NOTHING;
INSERT INTO notificacion_evento(idexamen,tipo,titulo,descripcion,fecha,clave)
SELECT idexamen,tipo,CASE WHEN tipo='AULA' THEN 'Cambio de aula' ELSE 'Cambio de horario' END,
 'Antes: '||anterior||'. Ahora: '||actual||'.',fecha,'cambio:'||id
FROM cambio_examen WHERE fecha >= CURRENT_TIMESTAMP - INTERVAL '30 days'
ON CONFLICT(clave) DO NOTHING;
INSERT INTO notificacion_evento(idexamen,destinatario,tipo,titulo,descripcion,fecha,clave)
SELECT idexamen,idayudante,'ASIGNACION','Asignación a examen','Asignación vigente incorporada a las notificaciones.',
 clock_timestamp(),'asignacion-inicial:'||idexamen||':'||idayudante
FROM ayudante_examen WHERE estado_asignacion='ACTIVO'
ON CONFLICT(clave) DO NOTHING;
