CREATE TABLE IF NOT EXISTS cambio_examen (
 id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 idexamen INTEGER NOT NULL REFERENCES examen(idexamen) ON DELETE CASCADE,
 tipo VARCHAR(10) NOT NULL CHECK (tipo IN ('AULA','HORARIO')),
 anterior TEXT NOT NULL,
 actual TEXT NOT NULL,
 fecha TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS cambio_examen_fecha_idx ON cambio_examen(fecha DESC);
