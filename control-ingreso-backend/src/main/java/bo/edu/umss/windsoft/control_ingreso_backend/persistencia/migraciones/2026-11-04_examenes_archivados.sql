BEGIN;
-- Biblioteca documental publica. Sin FK ni efectos sobre examenes, semestres o usuarios.
CREATE TABLE IF NOT EXISTS examen_pasado_documento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(200) NOT NULL CHECK(length(trim(titulo))>0),
    periodo VARCHAR(6) NOT NULL CHECK(periodo ~ '^[12]-[12][0-9]{3}$'),
    fecha DATE,
    observaciones VARCHAR(2000) NOT NULL DEFAULT '',
    pdf BYTEA NOT NULL CHECK(octet_length(pdf) BETWEEN 1 AND 10485760),
    sha256 VARCHAR(64) NOT NULL UNIQUE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS examen_pasado_documento_periodo_idx
    ON examen_pasado_documento((substring(periodo from 3)::integer) DESC, (substring(periodo from 1 for 1)::integer) DESC, fecha DESC, id DESC);
-- Sin politicas para clientes anon/authenticated de Supabase REST.
-- El backend accede por su conexion JDBC del propietario de la tabla.
ALTER TABLE examen_pasado_documento ENABLE ROW LEVEL SECURITY;
COMMIT;
