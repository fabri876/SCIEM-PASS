-- Migracion: Enrolamiento facial unico por estudiante y outbox de limpieza biometrica

-- 1. Crear tabla si no existe
CREATE TABLE IF NOT EXISTS limpieza_foto_biometrica (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ruta VARCHAR(500),
    foto_path VARCHAR(500),
    creado_en TIMESTAMP NOT NULL DEFAULT NOW()
);

-- 2. Asegurar columnas compatibles si la tabla ya existia previamente
ALTER TABLE limpieza_foto_biometrica ADD COLUMN IF NOT EXISTS ruta VARCHAR(500);
ALTER TABLE limpieza_foto_biometrica ADD COLUMN IF NOT EXISTS foto_path VARCHAR(500);
ALTER TABLE limpieza_foto_biometrica ADD COLUMN IF NOT EXISTS creado_en TIMESTAMP NOT NULL DEFAULT NOW();

-- Sincronizar columnas si una existia y la otra no
UPDATE limpieza_foto_biometrica SET ruta = foto_path WHERE ruta IS NULL AND foto_path IS NOT NULL;
UPDATE limpieza_foto_biometrica SET foto_path = ruta WHERE foto_path IS NULL AND ruta IS NOT NULL;

-- 3. Crear indice UNIQUE sobre ruta si no existe
CREATE UNIQUE INDEX IF NOT EXISTS uq_limpieza_foto_biometrica_ruta ON limpieza_foto_biometrica (ruta);

-- 4. Detectar y encolar fotos de registros duplicados anteriores para limpieza fisica
-- (Usa NOT EXISTS para ser 100% inmune a errores de ON CONFLICT)
INSERT INTO limpieza_foto_biometrica (ruta, foto_path, creado_en)
SELECT fe.photo_path, fe.photo_path, NOW()
FROM face_enrollment fe
WHERE fe.idenrollment NOT IN (
    SELECT DISTINCT ON (idusuario) idenrollment
    FROM face_enrollment
    ORDER BY idusuario, (estado = 'activo') DESC, fecha_registro DESC, idenrollment DESC
)
AND NOT EXISTS (
    SELECT 1 FROM limpieza_foto_biometrica lfb WHERE lfb.ruta = fe.photo_path
);

-- 5. Eliminar registros duplicados conservando el mas reciente / activo
DELETE FROM face_enrollment
WHERE idenrollment NOT IN (
    SELECT DISTINCT ON (idusuario) idenrollment
    FROM face_enrollment
    ORDER BY idusuario, (estado = 'activo') DESC, fecha_registro DESC, idenrollment DESC
);

-- 6. Aplicar la restriccion unica sobre idusuario
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'uq_face_enrollment_idusuario'
    ) THEN
        ALTER TABLE face_enrollment
            ADD CONSTRAINT uq_face_enrollment_idusuario UNIQUE (idusuario);
    END IF;
END $$;
