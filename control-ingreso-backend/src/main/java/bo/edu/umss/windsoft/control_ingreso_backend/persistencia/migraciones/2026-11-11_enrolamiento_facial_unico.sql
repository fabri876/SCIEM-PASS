-- Migracion: Enrolamiento facial unico por estudiante y outbox de limpieza biometrica

CREATE TABLE IF NOT EXISTS limpieza_foto_biometrica (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ruta VARCHAR(500) NOT NULL UNIQUE,
    creado_en TIMESTAMP NOT NULL
);

-- Detectar y encolar fotos de registros duplicados anteriores para limpieza fisica
INSERT INTO limpieza_foto_biometrica (ruta, creado_en)
SELECT fe.photo_path, NOW()
FROM face_enrollment fe
WHERE fe.idenrollment NOT IN (
    SELECT DISTINCT ON (idusuario) idenrollment
    FROM face_enrollment
    ORDER BY idusuario, (estado = 'activo') DESC, fecha_registro DESC, idenrollment DESC
)
ON CONFLICT (ruta) DO NOTHING;

-- Eliminar registros duplicados conservando el mas reciente / activo
DELETE FROM face_enrollment
WHERE idenrollment NOT IN (
    SELECT DISTINCT ON (idusuario) idenrollment
    FROM face_enrollment
    ORDER BY idusuario, (estado = 'activo') DESC, fecha_registro DESC, idenrollment DESC
);

-- Aplicar la restriccion unica sobre idusuario
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'uq_face_enrollment_idusuario'
    ) THEN
        ALTER TABLE face_enrollment
            ADD CONSTRAINT uq_face_enrollment_idusuario UNIQUE (idusuario);
    END IF;
END $$;
